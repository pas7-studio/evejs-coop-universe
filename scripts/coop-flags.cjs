"use strict";
// Co-op flag registry: the answer to "which gates exist and which are on?".
//
// The world is gated by hundreds of EVEJS_* switches. Without a registry, a
// typo in an env name, a copied legacy key or a silently renamed flag is
// invisible until a feature does nothing (or worse, does something) in a live
// session. This tool is read-only: it never sets env, never touches Docker.
//
// Usage:
//   node scripts/coop-flags.cjs --check
//     fail when a key appears in code that is not in docs/coop-flags.json
//   node scripts/coop-flags.cjs --baseline
//     rewrite docs/coop-flags.json from the current code (review the diff!)
//   node scripts/coop-flags.cjs --live --compose compose.yaml,compose.coop-probe.yaml
//     print the effective value of every declared key from compose files
const fs = require("node:fs");
const path = require("node:path");
const repo = path.resolve(__dirname, "..");
const BASELINE = path.join(repo, "docs", "coop-flags.json");
const KEY = /\bEVEJS_[A-Z0-9_]+\b/g;
const SOURCES = ["integration", "scripts", "patches"];

function walk(dir) {
  const out = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (/\.(c|m)?js$/.test(entry.name)) out.push(full);
  }
  return out;
}

function scan() {
  const readers = new Map();
  for (const dir of SOURCES) {
    for (const file of walk(path.join(repo, dir))) {
      const rel = path.relative(repo, file).replace(/\\/g, "/");
      const text = fs.readFileSync(file, "utf8");
      for (const match of text.match(KEY) || []) {
        const key = match;
        const list = readers.get(key) || [];
        if (!list.includes(rel)) list.push(rel);
        readers.set(key, list);
      }
    }
  }
  return readers;
}

function loadBaseline() {
  try {
    return JSON.parse(fs.readFileSync(BASELINE, "utf8"));
  } catch (_error) {
    return null;
  }
}

function baselineObject(readers) {
  const out = {};
  for (const key of [...readers.keys()].sort()) {
    out[key] = readers.get(key).length;
  }
  return { version: 1, note: "generated by scripts/coop-flags.cjs; review every new key", flags: out };
}

function unknown(readers, baseline) {
  const known = new Set(Object.keys(baseline?.flags || {}));
  return [...readers.keys()].filter((key) => !known.has(key)).sort();
}

function check({ quiet = false } = {}) {
  const readers = scan();
  const baseline = loadBaseline();
  if (!baseline) {
    console.log("FLAGS_MISSING_BASELINE (run --baseline once, then review the diff)");
    return 1;
  }
  const fresh = unknown(readers, baseline);
  const gone = Object.keys(baseline.flags).filter((key) => !readers.has(key));
  if (fresh.length) {
    console.log("FLAGS_UNDECLARED " + fresh.length);
    for (const key of fresh) console.log("  new", key, readers.get(key).join(","));
  }
  if (gone.length && !quiet) {
    console.log("FLAGS_STALE " + gone.length + " (declared but no longer read)");
    for (const key of gone.slice(0, 20)) console.log("  stale", key);
  }
  if (fresh.length) return 1;
  console.log("FLAGS_OK declared=" + Object.keys(baseline.flags).length +
    " read=" + readers.size + " stale=" + gone.length);
  return 0;
}

function composeFlags(files) {
  const values = new Map();
  for (const file of files) {
    const full = path.isAbsolute(file) ? file : path.join(repo, file);
    if (!fs.existsSync(full)) return { error: "COMPOSE_MISSING " + file };
    for (const line of fs.readFileSync(full, "utf8").split(/\r?\n/)) {
      const match = /^\s{2,}(EVEJS_[A-Z0-9_]+)\s*[:=]\s*([^#]*)$/.exec(line);
      if (match) values.set(match[1], (match[2] || "").trim().replace(/^['"]|['"]$/g, ""));
    }
  }
  return { values };
}

function main(argv) {
  const args = argv.slice(2);
  if (args.includes("--baseline")) {
    const data = baselineObject(scan());
    fs.writeFileSync(BASELINE, JSON.stringify(data, null, 1) + "\n");
    console.log("FLAGS_BASELINE_WRITTEN " + Object.keys(data.flags).length);
    return 0;
  }
  if (args.includes("--live")) {
    const index = args.indexOf("--compose");
    const files = index >= 0 && args[index + 1]
      ? args[index + 1].split(",").filter(Boolean)
      : ["compose.yaml", "compose.coop-probe.yaml"];
    const result = composeFlags(files);
    if (result.error) {
      console.log(result.error);
      return 1;
    }
    const baseline = loadBaseline();
    const declared = Object.keys(baseline?.flags || {});
    const on = [...result.values.entries()].filter(([, value]) => value === "1").map(([key]) => key);
    console.log("FLAGS_LIVE files=" + files.join(",") + " set=" + result.values.size +
      " on=" + on.length + " declared=" + declared.length);
    // Keys set in compose but never read by our own code are not an error:
    // they belong to upstream, or they are leftovers of a removed feature
    // (EVEJS_COOP_NPC_CAPACITOR was one). They are printed so an operator can
    // see what the world still carries, and never silently deleted by a tool.
    const notOurs = [...result.values.keys()].filter((key) => !declared.includes(key));
    for (const key of notOurs.sort()) console.log("  set-not-read", key, "=", result.values.get(key));
    return 0;
  }
  return check();
}

if (require.main === module) process.exitCode = main(process.argv);
module.exports = { scan, unknown, check, composeFlags, baselineObject, BASELINE };
