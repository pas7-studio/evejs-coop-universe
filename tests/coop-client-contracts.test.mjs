import test from "node:test";
import assert from "node:assert/strict";
import {execFileSync} from "node:child_process";
import {readFileSync} from "node:fs";
import path from "node:path";

// The register in docs/CLIENT_CONTRACT_STATUS.md is generated from the client's own call
// list (docs/client-contracts/calls.json) and the server handlers. This test fails when a
// client call that used to be answered starts getting a placeholder answer, or when a
// handler disappears - both are how the faction-warfare window broke in the first place.
const root = process.cwd();

test("no client call regressed to a missing or placeholder handler", () => {
  const output = execFileSync(process.execPath, [
    path.join(root, "scripts/coop-client-contracts.cjs"), "--check",
  ], {encoding: "utf8"});
  assert.match(output, /CONTRACTS_OK|CLIENT_CONTRACTS_REGRESSION/);
  assert.match(output, /CONTRACTS_OK/, output);
});

test("the register stays in step with the checker", () => {
  const baseline = JSON.parse(readFileSync(
    path.join(root, "docs/client-contracts/baseline.json"), "utf8"));
  assert.ok(Array.isArray(baseline.stubs), "the baseline lists the known placeholders");
  assert.ok(Array.isArray(baseline.missing));
  const register = readFileSync(path.join(root, "docs/CLIENT_CONTRACT_STATUS.md"), "utf8");
  assert.match(register, /Generated by `node scripts\/coop-client-contracts\.cjs --write`/);
  for (const key of baseline.stubs.slice(0, 5)) {
    assert.ok(register.includes("`" + key + "`"), key + " must appear in the register");
  }
});
